"""Erzeugt src/core/glyphs.js: Umrisse der Zeichen aus Liberation Sans Regular (SIL OFL 1.1)
als SVG-Pfade, damit die Beschriftung im SVG/PNG ohne installierte Schrift identisch aussieht.

Aufruf (einmalig, Ergebnis wird committet): python build/make-glyphs.py [Pfad/zu/LiberationSans-Regular.ttf]
Benötigt: pip install fonttools
"""
import json
import sys

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

font_path = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf'
f = TTFont(font_path)
gs = f.getGlyphSet()
cmap = f.getBestCmap()
os2 = f['OS/2']

chars = [chr(c) for c in range(32, 127)] + list('ÄÖÜäöüß€–·°')
out = {}
for ch in chars:
    g = cmap.get(ord(ch))
    if not g:
        continue
    pen = SVGPathPen(gs, ntos=lambda v: ('%.0f' % v) if v == int(v) else ('%.1f' % v))
    gs[g].draw(TransformPen(pen, (1, 0, 0, -1, 0, 0)))  # Font: y nach oben, SVG: y nach unten
    out[ch] = [gs[g].width, pen.getCommands()]

meta = {'upm': f['head'].unitsPerEm, 'capHeight': os2.sCapHeight,
        'ascender': os2.sTypoAscender, 'descender': os2.sTypoDescender}
js = ("/* Glyph outlines from Liberation Sans Regular (SIL Open Font License 1.1), generated by build/make-glyphs.py */\n"
      "(function (root) {\n  var QRC = root.QRC = root.QRC || {};\n  QRC.glyphs = "
      + json.dumps({'meta': meta, 'g': out}, ensure_ascii=False, separators=(',', ':'))
      + ";\n})(typeof window !== 'undefined' ? window : globalThis);\n")
with open('src/core/glyphs.js', 'w', encoding='utf-8') as fh:
    fh.write(js)
print('src/core/glyphs.js', len(js), 'Bytes')
